/** Варианты вопроса, которому вариантов ещё не искали: добавлен на «Вопросах» после их утверждения. */
export const noOptions = (): MockOptionSet => set('', [], null);

/** Свой вариант — как в контракте: «P» и номер на один больше самого большого номера вариантов потока. */
export function ownOption(sets: MockOptionSet[], text: string, basedOn: string | null): Option {
  const numbers = sets.flatMap((s) => s.options.map((o) => Number(/^P(\d+)$/.exec(o.id)?.[1] ?? 0)));
  return own(`P${Math.max(0, ...numbers) + 1}`, text.trim(), basedOn);
}
