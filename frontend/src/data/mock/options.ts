/**
 * Варианты на вопрос в моках — без самого вопроса: вопрос берётся из вопросов потока, как его видит «Вопросы»; без
 * круга зависимостей: его, как и порядок вопросов, моки считают по зависимостям вариантов (order.ts); и без unchecked:
 * его моки считают по решениям потока (index.ts).
 */
export type MockOptionSet = Omit<OptionSet, 'question' | 'cycle' | 'unchecked'>;

/** Вариант совета: без цены и зависимостей, не рекомендован, если не сказано другое. */
const option = (
  id: string,
  text: string,
  source: OptionSource,
  reason: string | null,
  extra: Partial<Pick<Option, 'recommended' | 'cost' | 'dependsOn' | 'basedOn'>> = {},
): Option => ({ id, text, source, recommended: false, reason, cost: null, dependsOn: [], basedOn: null, ...extra });

/** Свой вариант человека: «почему», цены и зависимостей пока нет — их допишет совет. */
const own = (id: string, text: string, basedOn: string | null): Option =>
  option(id, text, 'user', null, { basedOn });

const chose = (id: string): Choice => ({ kind: 'option', option: id });
const UNRESOLVED: Choice = { kind: 'unresolved' };

