/** Новая заметка без ссылок на решения проекта. */
const note = (id: string, type: NoteType, title: string, extra: Partial<Note> = {}): Note => ({
  id,
  type,
  title,
  change: 'new',
  revisits: null,
  supersedes: null,
  supersededBy: null,
  ...extra,
});

/** Заметки нескольких одного вида — новые, по порядку. */
const many = (type: NoteType, list: [id: string, title: string][]): Note[] =>
  list.map(([id, title]) => note(id, type, title));

