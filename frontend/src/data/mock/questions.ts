/** Фрагменты по id: фрагмент-предложение в вопросе — тот же, что у нарезки. */
const pick = (fragments: Fragment[], ids: string[]): Fragment[] =>
  ids.flatMap((id) => fragments.filter((fragment) => fragment.id === id));

